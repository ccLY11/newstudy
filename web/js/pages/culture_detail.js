export async function render(root, params = {}) {
	const info = CULTURE_LIST.find(c => String(c.id) === String(params.id));
	const detail = CULTURE_DETAIL.find(c => String(c.id) === String(params.id));
	if (!info || !detail) { root.innerHTML = empty('内容不存在'); return; }

	const ps = t => String(t).split(/\n/).filter(s => s.trim() !== '').map(s => '<p>' + esc(s) + '</p>').join('');
	root.innerHTML = `
		<img class="cover-big" src="${info.cover}" onerror="this.style.opacity=.3">
		<div class="detail-top">
			<h1 style="font-size: 17px;">${esc(info.title)}</h1>
			<div class="detail-meta"><span class="tag red">文化教育</span></div>
		</div>
		<div class="detail-body">
			<p style="color: var(--text-grey); font-size: 13px;">${esc(info.description)}</p>
			${ps(detail.content)}
		</div>
		<div class="card">
			<div class="card-title">相关主题</div>
			<div style="display: flex; flex-wrap: wrap; gap: 8px; padding: 0 14px 14px;">
				${detail.relatedTopics.map(t => `<span class="tag red">${esc(t)}</span>`).join('')}
			</div>
		</div>
	`;
}
